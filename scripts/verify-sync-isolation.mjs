// Operator-only acceptance check for two designated disposable account IDs.
// All RPCs are scoped by verified user tokens. Never use an admin credential.
import { createCipheriv, createHash, randomBytes, randomUUID } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { DesktopAccount, accountOrigin, projectRef } from '../dist/desktop-account.js';

const contract = 'growthbrain.sync.v1';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const requireCheck = (condition, code) => { if (!condition) throw Error(code); };
const newFile = (path, body) => writeFile(path, body, { flag: 'wx', mode: 0o600 });
function box(bytes) {
  const iv = randomBytes(12), key = randomBytes(32);
  try {
    const cipher = createCipheriv('aes-256-gcm', key, iv);
    const ciphertext = Buffer.concat([cipher.update(Buffer.alloc(bytes)), cipher.final()]);
    return { iv: iv.toString('base64'), tag: cipher.getAuthTag().toString('base64'), ciphertext: ciphertext.toString('base64') };
  } finally { key.fill(0); }
}
const sample = (prior, bodySize = 40) => ({ version: 1, sequence: 1, parentRevision: prior, vaultId: randomUUID(), wrapped: box(32), body: box(bodySize) });

async function qualifiedCatalog(path) {
  const bytes = await readFile(path);
  requireCheck(bytes.length <= 65536, 'CATALOG_INVALID');
  const record = JSON.parse(bytes);
  const ddl = await readFile(new URL('./proposed/account-sync-v1.sql', import.meta.url));
  const pin = (await readFile(new URL('./proposed/account-sync-catalog.sha256', import.meta.url),'utf8')).trim();
  requireCheck(record.kind === 'growthbrain-sync-catalog' && record.catalogVerified === true &&
    record.projectRef === projectRef && record.contract === contract && record.readOnlyVerified === true &&
    record.applicationRowsRead === false && record.catalogSha256 === pin && record.contractSha256 === sha256(ddl), 'CATALOG_UNVERIFIED');
  return { projectRef, contract, catalogSha256: pin, contractSha256: sha256(ddl), catalogReportSha256: sha256(bytes) };
}

export async function verifyIsolation({ publicKey, credentials, catalogPath, destination, fetcher = fetch }) {
  const catalog = await qualifiedCatalog(catalogPath);
  requireCheck(credentials.length === 2 && credentials[0].id && credentials[1].id &&
    credentials[0].id !== credentials[1].id && credentials.every(a => a.email && a.password), 'DISPOSABLE_ACCOUNTS_REQUIRED');
  await mkdir(destination, { mode: 0o700 }); // Never overwrite or reuse an evidence directory.
  const clients = credentials.map(() => new DesktopAccount(publicKey, fetcher));
  const checks = {};
  const observations = [];
  const purgeAttempted = new Set();
  const owned = []; // Only exact synthetic snapshots generated by this run are eligible for cleanup.
  const rpc = async (index, operation, args = {}) => {
    const headers = { apikey: publicKey, 'content-type': 'application/json' };
    if (index !== null) headers.authorization = 'Bearer ' + await clients[index].accessToken();
    const response = await fetcher(accountOrigin + '/rest/v1/rpc/growthbrain_sync_v1_' + operation,
      { method:'POST', headers, body:JSON.stringify(args), redirect:'error', signal:AbortSignal.timeout(20000) });
    // No provider response, token, email or account ID is logged.
    observations.push({account:index === null ? 'anonymous' : index === 0 ? 'A' : 'B', operation, status:response.status});
    const body = await response.json();
    if (response.ok) requireCheck(body.contract === contract, 'UNEXPECTED_CONTRACT');
    return { status:response.status, body };
  };
  const read = async index => {
    const { status, body } = await rpc(index, 'read');
    requireCheck(status === 200 && Object.hasOwn(body, 'payload') &&
      (body.revision === null || typeof body.revision === 'string') && Number.isSafeInteger(body.bytes) &&
      Number.isSafeInteger(body.quota), 'READ_FAILED');
    return body;
  };
  const expectConflict = async (index, op, args) => {
    const result = await rpc(index, op, args);
    requireCheck(result.status === 409 && result.body.code === 'PT409', 'CONFLICT_NOT_ENFORCED');
  };
  const purgeOwn = async index => {
    const expected = owned[index];
    if (!expected) return;
    const current = await read(index);
    if (current.payload === null) return;
    requireCheck(isDeepStrictEqual(current.payload, expected), 'CONTENT_CHANGED_NO_CLEANUP');
    requireCheck(!purgeAttempted.has(current.revision), 'PREVIOUS_PURGE_UNCERTAIN');
    purgeAttempted.add(current.revision);
    const purged = await rpc(index, 'purge', { expected_revision:current.revision });
    requireCheck(purged.status === 200 && purged.body.bytes === 0 &&
      purged.body.revision !== current.revision, 'PURGE_UNCONFIRMED');
    owned[index] = null;
  };

  let passed = false;
  let cleanupOk = true;
  try {
    for (const [i, c] of credentials.entries()) {
      const login = await clients[i].login(c.email, c.password);
      login.wrappingKey.fill(0);
      requireCheck(login.userId === c.id, 'DISPOSABLE_ID_MISMATCH');
    }
    checks.verifiedDistinctAccounts = true;
    const anon = await rpc(null, 'status');
    requireCheck([401,403].includes(anon.status), 'ANON_ALLOWED');
    checks.anonymousDenied = true;
    for (const i of [0,1]) {
      const status = await rpc(i, 'status');
      requireCheck(status.status === 200 && status.body.bytes === 0, 'DISPOSABLE_ACCOUNTS_NOT_EMPTY');
    }
    const a = await read(0), b = await read(1);
    requireCheck([a,b].every(s => s.bytes === 0 && s.payload === null), 'DISPOSABLE_ACCOUNTS_NOT_EMPTY');
    requireCheck(a.quota >= 1024 && b.quota >= 1024 && b.quota <= 1024*1024, 'BOUNDED_TEST_QUOTA_REQUIRED');

    const first = sample(a.revision);
    owned[0] = first;
    const uploaded = await rpc(0,'write',{expected_revision:a.revision,payload:first});
    const prior = uploaded.body.revision;
    requireCheck(uploaded.status === 200 && prior && prior !== a.revision &&
      isDeepStrictEqual((await read(0)).payload, first), 'WRITE_UNCONFIRMED');
    const other = await read(1);
    requireCheck(other.bytes === 0 && other.payload === null && other.revision === b.revision, 'ACCOUNT_READ_ISOLATION_FAILED');
    checks.crossAccountReadDenied = true;

    // A revision belonging to A must not authorize a write or purge from B.
    const next = {...first, parentRevision:prior, sequence:2, body:box(40)};
    await expectConflict(1,'write',{expected_revision:prior,payload:next});
    checks.crossAccountWriteDenied = true;
    await expectConflict(1,'purge',{expected_revision:prior});
    checks.crossAccountPurgeDenied = true;
    requireCheck(isDeepStrictEqual((await read(0)).payload, first) && (await read(1)).payload === null, 'CROSS_ACCOUNT_CHANGED');
    await expectConflict(0,'write',{expected_revision:a.revision,payload:first});
    checks.staleRevisionRejected = true;

    const tooLarge = sample(b.revision, b.quota);
    owned[1] = tooLarge;
    const rejected = await rpc(1,'write',{expected_revision:b.revision,payload:tooLarge});
    requireCheck(rejected.status === 413 && rejected.body.code === 'PT413' && (await read(1)).payload === null, 'QUOTA_NOT_ENFORCED');
    owned[1] = null;
    checks.quotaEnforced = true;

    await purgeOwn(0);
    // If the contract erroneously accepts this stale upload, it's still our
    // synthetic record. Verify its content before trying to clean it up.
    owned[0] = next;
    await expectConflict(0, 'write', {expected_revision:prior,payload:next});
    requireCheck((await read(0)).payload === null, 'PURGE_STALE_WRITE_ALLOWED');
    checks.purgePreventsStaleUpload = true;
    owned[0] = null;
    passed = true;
  } finally {
    for (let i=0;i<clients.length;i++) {
      try { await purgeOwn(i); } catch { cleanupOk = false; }
      try { await clients[i].logout(); } catch { cleanupOk = false; }
    }
    const evidence = JSON.stringify({projectRef,contract,completedAt:new Date().toISOString(),checks,observations,
      passed:passed && cleanupOk, cleanupConfirmed:cleanupOk},null,2)+'\n';
    await newFile(join(destination,'run-evidence.json'),evidence);
    if (!cleanupOk) throw Error('CHECK_DISPOSABLE_ACCOUNTS_NO_RETRY');
    if (passed) {
      await newFile(join(destination,'isolation-review.json'),JSON.stringify({...catalog,
        kind:'growthbrain-sync-isolation-review-v1',runEvidenceSha256:sha256(evidence),checks},null,2)+'\n');
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.length !== 4 || process.argv[2] !== '--disposable-accounts') {
    console.error('Usage: node scripts/verify-sync-isolation.mjs --disposable-accounts <new-evidence-directory>');
    process.exitCode = 1;
  } else {
    const env = process.env;
    const accounts = ['A','B'].map(label => ({
      id:env['GB_TEST_ACCOUNT_'+label+'_ID'], email:env['GB_TEST_ACCOUNT_'+label+'_EMAIL'], password:env['GB_TEST_ACCOUNT_'+label+'_PASSWORD'],
    }));
    try {
      await verifyIsolation({ credentials:accounts, publicKey:env.GROWTH_BRAIN_SUPABASE_PUBLISHABLE_KEY,
        catalogPath:env.GROWTH_BRAIN_SYNC_CATALOG_REPORT, destination:process.argv[3] });
      console.log('Disposable account verification passed. Preserve the evidence directory with this build.');
    } catch {
      console.error('Isolation verification failed. Preserve any evidence, inspect the designated test accounts and check the catalog, identity and quota prerequisites before a new run.');
      process.exitCode = 1;
    }
  }
}
