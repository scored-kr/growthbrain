import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID, randomBytes } from 'node:crypto';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { VaultSession } from '../dist/vault.js';
import { startBroker, callBroker } from '../dist/broker.js';
import { proposal, approve } from './helpers.mjs';

test('real stdio MCP transport retrieves scoped memory, records candidates, denies approval and fails closed when locked',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'gb-mcp-'));
  const owner=randomUUID(), password=randomBytes(24).toString('base64url');
  const vault=await VaultSession.open(directory,owner,password,true);
  const project=await vault.mutate(e=>e.addProject('Synthetic marketer campaign'));
  const other=await vault.mutate(e=>e.addProject('Other customer'));
  await vault.mutate(e=>{
    approve(e,proposal({type:'global'},'language','한국어'));
    approve(e,proposal({type:'global'},'tone','친근하게'));
    const old=approve(e,proposal({type:'project',projectId:project.id},'cta','지금 구매'));
    approve(e,proposal({type:'project',projectId:project.id},'cta','무료 상담',{supersedesId:old}));
    approve(e,proposal({type:'project',projectId:project.id},'tone','과장 없는 전문적인 어조'));
    approve(e,proposal({type:'project',projectId:project.id},'budget','월 50만원 이하'));
    approve(e,proposal({type:'project',projectId:other.id},'secret','OTHER_PROJECT_SECRET'));
  });
  const broker=await startBroker(vault,directory);
  const client=new Client({name:'synthetic-protocol-test',version:'1.0.0'});
  const transport=new StdioClientTransport({command:process.execPath,args:[resolve('dist/mcp.js')],env:{GROWTH_BRAIN_SOCKET:broker.path},stderr:'pipe'});
  let stderr='';transport.stderr.on('data',chunk=>{stderr+=chunk});
  t.after(async()=>{await client.close();await broker.close().catch(()=>{});await vault.close();await rm(directory,{recursive:true,force:true});});
  await client.connect(transport);
  const tools=(await client.listTools()).tools;
  assert.deepEqual(tools.map(t=>t.name).sort(),['get_context','propose_memory','search_memory']);
  assert.ok(!JSON.stringify(tools).includes('password'));
  const invoke=async(name,args)=>{
    const r=await client.callTool({name,arguments:args});
    return {raw:r,value:JSON.parse(r.content[0].text)};
  };
  const first=await invoke('get_context',{projectId:project.id});
  const root=await invoke('get_context',{});
  assert.deepEqual(root.value.searchedScopes,['global']);assert.equal(root.value.projectId,null);
  assert.deepEqual(root.value.conditions.map(m=>m.key).sort(),['language','tone']);
  await vault.mutate(e=>e.configureProjectTriggers(project.id,['테스트캠페인']));
  const routed=await invoke('get_context',{query:'테스트캠페인의 다음 작업'});
  assert.equal(routed.value.projectId,project.id);assert.equal(routed.value.routing.reason,'configured_trigger');
  const rootSearch=await invoke('search_memory',{query:'언어'});
  assert.equal(rootSearch.value.matches[0].value,'한국어');assert.deepEqual(rootSearch.value.searchedScopes,['global']);
  assert.ok(!first.raw.isError);
  assert.equal(first.value.conditions.find(x=>x.key==='language').value,'한국어');
  assert.equal(first.value.conditions.find(x=>x.key==='tone').value,'과장 없는 전문적인 어조');
  assert.equal(first.value.conditions.find(x=>x.key==='cta').value,'무료 상담');
  assert.ok(!JSON.stringify(first).includes('OTHER_PROJECT_SECRET'));
  const topicSearch=await invoke('search_memory',{projectId:project.id,query:'돈을 얼마나 써도 돼'});
  assert.equal(topicSearch.value.retrieval,'local-lexical-topic-v2');
  assert.equal(topicSearch.value.matches[0].value,'월 50만원 이하');
  assert.deepEqual(topicSearch.value.matches[0].matchedTopics,['budget']);
  assert.deepEqual((await invoke('search_memory',{projectId:project.id,query:'얼마까지 쓸 수 있지',requestConditions:{budget:'이번 요청에서 지정한 한도'}})).value.matches,[]);
  assert.deepEqual((await invoke('search_memory',{projectId:project.id,query:'지금 구매'})).value.matches,[]);
  const p=await invoke('propose_memory',proposal({type:'project',projectId:project.id},'style','CANDIDATE_ONLY',{source:{kind:'ai',reference:'synthetic:ai',excerpt:'inferred style'}}));
  assert.equal(p.value.status,'candidate');
  assert.equal(p.value.reviewRequired,true);
  assert.ok(!JSON.stringify((await invoke('get_context',{projectId:project.id})).value).includes('CANDIDATE_ONLY'));
  await assert.rejects(callBroker(broker.path,'approve_memory',{id:p.value.id}),/INVALID_REQUEST/);
  const forbidden=await client.callTool({name:'propose_memory',arguments:{...proposal({type:'global'},'style','bad'),status:'active'}});
  assert.equal(forbidden.isError,true);
  await vault.mutate(e=>e.review(p.value.id,'approve'));
  assert.equal((await invoke('search_memory',{projectId:project.id,query:'CANDIDATE_ONLY'})).value.matches.length,1);
  const override=await invoke('get_context',{projectId:project.id,requestConditions:{tone:'이번에는 짧게'}});
  assert.equal(override.value.conditions.find(x=>x.key==='tone').value,'이번에는 짧게');
  const persisted=await readFile(join(directory,'vault.json'),'utf8');
  const requestConditions={tone:'이번에는 짧게',cta:'이번에는 안내만'};
  for(const query of ['전문적인','친근하게','무료 상담','이번에는','OTHER_PROJECT_SECRET']) {
    const search=await invoke('search_memory',{projectId:project.id,query,requestConditions});
    assert.ok(!search.raw.isError);
    assert.deepEqual(search.value.matches,[]);assert.equal(search.value.omittedCount,0);
    assert.deepEqual(search.value.searchedScopes,['global',`project:${project.id}`]);
  }
  assert.equal((await invoke('search_memory',{projectId:project.id,query:'한국어',requestConditions})).value.matches.length,1);
  assert.equal((await invoke('search_memory',{projectId:project.id,query:'전문적인'})).value.matches.length,1);
  const excessive=Object.fromEntries(Array.from({length:51},(_,i)=>[`key_${i}`,'synthetic override']));
  const rejectedOverride=await invoke('search_memory',{projectId:project.id,query:'한국어',requestConditions:excessive});
  assert.equal(rejectedOverride.raw.isError,true);
  assert.equal(rejectedOverride.value.error,'REQUEST_CONDITION_LIMIT');
  assert.equal(await readFile(join(directory,'vault.json'),'utf8'),persisted);
  assert.ok(!(await readFile(join(directory,'vault.json'),'utf8')).includes('CANDIDATE_ONLY'));
  await vault.close();
  const locked=await invoke('get_context',{projectId:project.id});
  assert.equal(locked.raw.isError,true);assert.equal(locked.value.error,'VAULT_LOCKED');
  const lockedSearch=await invoke('search_memory',{projectId:project.id,query:'한국어',requestConditions});
  assert.equal(lockedSearch.raw.isError,true);assert.equal(lockedSearch.value.error,'VAULT_LOCKED');
  assert.ok(!stderr.includes(password));assert.ok(!stderr.includes('CANDIDATE_ONLY'));
});
